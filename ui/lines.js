let PERSONALITY = 'normal';
function L(key, vars = {}) {
  const set = LINES[PERSONALITY] || LINES.normal;
  const opts = set[key] || LINES.normal[key] || [key];
  const line = opts[Math.floor(Math.random() * opts.length)];
  return line.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
}
